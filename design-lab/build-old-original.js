/* Builds OLD-ORIGINAL/index.html — the shipped design, harnessed and seeded.
 *
 * WHY A SEPARATE SCRIPT. build.js writes into design-lab/ and refuses to touch a
 * file that already exists, because every file it has produced was redesigned by
 * hand afterwards. This one writes somewhere else entirely and is safe to re-run:
 * OLD-ORIGINAL is a copy, never a thing anyone designs on. If it is ever worked
 * on by hand, stop re-running this.
 *
 * WHAT IT IS FOR. Side by side review. The reviewer opens the old design and the
 * new one with the SAME invented records in both, so what they are comparing is
 * the design and nothing else.
 *
 * The harness matches build.js line for line in what it does - its own
 * localStorage namespace, no GitHub, no service worker, a badge saying what this
 * is - because a review copy that could touch the real Spendly is not a review
 * copy.
 */
const fs = require("fs"), path = require("path");
const ROOT = path.resolve(__dirname, "..");
const OUT_DIR = path.join(ROOT, "OLD-ORIGINAL");
const src = fs.readFileSync(path.join(ROOT, "index.html"), "utf8");
const SEED = fs.readFileSync(path.join(__dirname, "seed-data.json"), "utf8");

const NS = "LAB_ORIGINAL_";
const STAMP = "2026-09-18/loans-44-repaid-on";

const harness = `
<!-- ===========================================================================
     OFFLINE REVIEW HARNESS — not part of the live app, and not part of the design.
     Generated by design-lab/build-old-original.js; do not hand-edit. Everything
     here exists so this copy can be opened, poked at and thrown away without
     touching the real Spendly.
     ======================================================================== -->
<script>
(function(){
  "use strict";
  var NS = ${JSON.stringify(NS)};

  /* ---- its own corner of localStorage --------------------------------------
     Every key the app writes starts with spendly_, so prefixing exactly those
     keeps this copy's records and the real ones in separate drawers of the same
     origin. Anything else the page stores is left where it is. */
  var _get = Storage.prototype.getItem,
      _set = Storage.prototype.setItem,
      _del = Storage.prototype.removeItem;
  function ns(k){ return (typeof k === "string" && k.indexOf("spendly_") === 0) ? NS + k : k; }
  Storage.prototype.getItem    = function(k){ return _get.call(this, ns(k)); };
  Storage.prototype.setItem    = function(k, v){ return _set.call(this, ns(k), v); };
  Storage.prototype.removeItem = function(k){ return _del.call(this, ns(k)); };

  /* ---- no network, in either direction -------------------------------------
     Sync is off by default, but a review copy must not be able to reach a gist
     even if someone presses the button. */
  var _fetch = window.fetch;
  window.fetch = function(input){
    var url = typeof input === "string" ? input : (input && input.url) || "";
    if (/api\\.github\\.com/.test(url)){
      return Promise.reject(new Error("Blocked in the review copy: no GitHub from here."));
    }
    return _fetch.apply(this, arguments);
  };

  /* ---- and no service worker ----------------------------------------------
     One registered against this origin would serve the real app's cached files
     to this page, and this page's to the real app. */
  try {
    if (navigator.serviceWorker){
      navigator.serviceWorker.getRegistrations().then(function(rs){
        rs.forEach(function(r){ r.unregister(); });
      }).catch(function(){});
    }
  } catch (e){}
  try {
    Object.defineProperty(navigator, "serviceWorker", { configurable: true, get: function(){ return undefined; } });
  } catch (e){}

  /* ---- the same records as the new design ----------------------------------
     Invented, every one of them. The point of the copy is that the reviewer is
     looking at two designs of the same data. */
  var SEED = ${SEED};
  var SEED_STAMP = ${JSON.stringify(STAMP)};
  try {
    if (!localStorage.getItem("spendly_expenses_v1") ||
        localStorage.getItem("spendly_lab_seed_stamp_v1") !== SEED_STAMP){
      for (var k in SEED){
        if (Object.prototype.hasOwnProperty.call(SEED, k)) localStorage.setItem(k, JSON.stringify(SEED[k]));
      }
      localStorage.setItem("spendly_lab_seed_stamp_v1", SEED_STAMP);
    }
  } catch (e){}

  /* ---- a way to put it back the way it was --------------------------------- */
  window.__labReset = function(){
    var doomed = [];
    for (var i = 0; i < localStorage.length; i++){
      var key = localStorage.key(i);
      if (key && key.indexOf(NS) === 0) doomed.push(key);
    }
    doomed.forEach(function(key){ _del.call(localStorage, key); });
    location.reload();
  };
})();
</script>
`;

const badge = `
<div id="lab-badge" role="note">
  <strong>OLD ORIGINAL</strong>
  <small>the design as shipped — for comparison only</small>
  <button type="button" onclick="window.__labReset()">reset</button>
</div>
<style>
  #lab-badge{
    position: fixed; left: 10px; bottom: 10px; z-index: 2147483000;
    display: flex; align-items: center; gap: 8px;
    max-width: calc(100vw - 20px);
    padding: 6px 10px; border-radius: 999px;
    background: #2b1d00; color: #ffd479; border: 1px solid #7a5a12;
    font: 600 11px/1.3 ui-sans-serif, system-ui, sans-serif;
    letter-spacing: .02em; pointer-events: none;
  }
  #lab-badge strong{ letter-spacing: .08em; }
  #lab-badge small{ opacity: .65; font-weight: 500; }
  #lab-badge button{
    pointer-events: auto; cursor: pointer;
    background: transparent; border: 1px solid #7a5a12; color: inherit;
    border-radius: 999px; padding: 1px 7px; font: inherit; font-size: 10px;
  }
  @media (max-width: 720px){
    #lab-badge{ bottom: auto; top: 6px; left: 6px; font-size: 10px; padding: 4px 8px; }
    #lab-badge small{ display: none; }
  }
</style>
`;

const SW_BLOCK = `if ("serviceWorker" in navigator &&
    (location.protocol === "https:" || location.hostname === "localhost" || location.hostname === "127.0.0.1")){
  window.addEventListener("load", ()=>{
    navigator.serviceWorker.register("./sw.js").catch(()=>{});
  });
}`;

let out = src;

const at = out.indexOf("<script>");
if (at < 0) throw new Error("no script tag in index.html");
out = out.slice(0, at) + harness + out.slice(at);

if (out.indexOf(SW_BLOCK) < 0) throw new Error("service worker block not found");
out = out.replace(SW_BLOCK, "/* Service worker registration removed: this is an offline review copy. */");

// One folder down, so the icon and the manifest still resolve.
["./icon-180.png", "./icon.svg", "./manifest.webmanifest"].forEach(ref => {
  const hits = out.split('"' + ref + '"').length - 1;
  if (!hits) throw new Error("expected to find " + ref);
  out = out.split('"' + ref + '"').join('"../' + ref.slice(2) + '"');
});

const end = out.lastIndexOf("</body>");
if (end < 0) throw new Error("no </body>");
out = out.slice(0, end) + badge + out.slice(end);

if (!/<\/html>\s*$/.test(out)) throw new Error("result does not end in </html>");

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(path.join(OUT_DIR, "index.html"), out);
console.log("  built  OLD-ORIGINAL/index.html   ns=" + NS +
  "   (" + out.split("\n").length + " lines, from index.html at " +
  src.split("\n").length + ")");
